import { readFileSync, writeFileSync, existsSync, readdirSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { themes } from '../src/appearance.mjs';
const read = (p) => readFileSync(p, 'utf8'),
  pkg = JSON.parse(read('package.json')),
  server = read('server.mjs'),
  main = read('src/main.jsx');
const nav = main.match(/const nav\s*=\s*\[([\s\S]*?)\];/)[1],
  pages = [...nav.matchAll(/\[\s*['"]([^'"]+)['"]\s*,\s*\w+\s*\]/g)].map((m) => m[1]);
const endpoints = [...server.matchAll(/app\.(get|post|put|delete)\(\s*['"]([^'"]+)['"]/g)].map(
  (m) => [m[1].toUpperCase(), m[2]],
);
const env = [
  ...new Set(
    ['server.mjs', 'vite.config.js'].flatMap((p) =>
      [...read(p).matchAll(/process\.env\.([A-Z_]+)/g)].map((m) => m[1]),
    ),
  ),
].sort();
const collections = ['profiles', 'bills', 'debts', 'payments', 'expenses', 'tasks'];
const generated = `# Code reference\n\n<!-- Generated by npm run docs:generate. Do not edit manually. -->\n\nThis reference is derived from the current source. CI rejects stale output.\n\n## Runtime and packages\n\n- Node.js: \`${pkg.engines.node}\`\n- React: \`${pkg.dependencies.react}\`\n- Express: \`${pkg.dependencies.express}\`\n- Vite: \`${pkg.devDependencies.vite}\`\n- Persistence: Node.js built-in SQLite\n\n## Navigation\n\n${pages.map((p) => '- ' + p).join('\n')}\n- Settings & profiles\n\nOverview includes the monthly cash-flow breakdown and extra spending.\n\n## HTTP routes\n\nRoutes are relative to the application mount point. The auth action accepts \`register\` or \`login\`. See [architecture](ARCHITECTURE.md) for trust boundaries.\n\n| Method | Path |\n| --- | --- |\n${endpoints.map(([method, path]) => `| ${method} | \`${path}\` |`).join('\n')}\n\n## Environment variables read by the application\n\n${env.map((v) => '- `' + v + '`').join('\n')}\n\nSee [deployment](DEPLOYMENT.md) for defaults and safe configuration.\n\n## Account state collections\n\n${collections.map((v) => '- `' + v + '`').join('\n')}\n\nIncome changes, bill versions and paid snapshots are nested in their profile/bill records. Appearance preferences are account-level; tracker preferences are profile-level.\n\n## Appearance\n\n${themes.map((t) => '- ' + t.name + ' (`' + t.id + '`)').join('\n')}\n\nEach theme supports light, dark and system appearance.\n\n## npm commands\n\n| Command | Implementation |\n| --- | --- |\n${Object.entries(
  pkg.scripts,
)
  .map(([name, command]) => `| \`npm run ${name}\` | \`${command}\` |`)
  .join('\n')}\n`;
const path = 'docs/REFERENCE.md';
if (process.argv.includes('--write')) {
  writeFileSync(path, generated);
  console.log('Updated ' + path);
} else if (!existsSync(path) || read(path) !== generated) {
  console.error(
    'Generated documentation is stale. Run npm run docs:generate and commit docs/REFERENCE.md.',
  );
  process.exitCode = 1;
}
// Check repository-local Markdown links. External links are not network-tested.
for (const file of [
  'README.md',
  'SECURITY.md',
  'CONTRIBUTING.md',
  ...readdirSync('docs')
    .filter((f) => f.endsWith('.md'))
    .map((f) => 'docs/' + f),
]) {
  if (!existsSync(file)) continue;
  for (const match of read(file).matchAll(/!?\[[^\]]*\]\(([^)]+)\)/g)) {
    const target = match[1].split('#')[0];
    if (!target || /^(?:https?:|mailto:|data:)/.test(target)) continue;
    const dest = resolve(dirname(file), decodeURIComponent(target));
    if (!existsSync(dest)) {
      console.error(`Broken local link in ${file}: ${target}`);
      process.exitCode = 1;
    }
  }
}
